-- ---------------------------------------------------------------------
-- Yuklenen lab senaryolarinin ozeti
-- ---------------------------------------------------------------------
SELECT lab_case,
       count(*) AS row_count,
       string_agg(DISTINCT table_name, ', ' ORDER BY table_name) AS tables
FROM lab_objects
GROUP BY lab_case
ORDER BY lab_case;
