-- CONTROLLED ANOMALY LAB
--
-- Bu dosya ana seed'in PARCASI DEGILDIR ve ana seed'i bozmaz.
-- Amac: reconciliation ve data correction calismalari (Module 7 ve
-- buggy query review programi) icin BELGELENMIS, RESETLENEBILIR
-- is-kurali ihlalleri uretmek.
--
-- Onemli ayrim:
--   * Ana seed  -> "valid but tricky": NULL, zero-child parent, ayni
--                  timestamp, coklu payment attempt, partial refund,
--                  split shipment. Hepsi YASAL veridir.
--   * Bu dosya  -> "controlled anomaly": constraint'leri ihlal etmeyen
--                  ama BUSINESS kurallarini ihlal eden kayitlar.
--
-- Idempotent: dosyayi tekrar calistirmak once onceki lab kayitlarini
-- siler, sonra yeniden uretir. Sadece INSERT yapar; mevcut seed
-- satirlarini asla UPDATE etmez.
--
-- Temizlemek icin:  SELECT commerceops.lab_reset();
-- =====================================================================

SET search_path = commerceops, public;

CREATE TABLE IF NOT EXISTS lab_objects (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_case   text        NOT NULL,
    table_name text        NOT NULL,
    row_id     bigint      NOT NULL,
    note       text,
    created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE lab_objects IS 'Anomaly lab kayit defteri. Reset bu tabloya gore yapilir.';

-- ---------------------------------------------------------------------
-- Reset: kayitli lab satirlarini FK'ye guvenli sirayla siler
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION lab_reset()
RETURNS text
LANGUAGE plpgsql
SET search_path = commerceops, public
AS $$
DECLARE
    r          record;
    deleted    integer := 0;
    tbl_order  text[] := ARRAY['reviews','shipment_items','shipments','inventory_movements',
                               'refunds','payments','order_status_history','order_items',
                               'orders','merchant_members'];
    t          text;
    n          integer;
BEGIN
    FOREACH t IN ARRAY tbl_order LOOP
        FOR r IN SELECT row_id FROM lab_objects WHERE table_name = t LOOP
            EXECUTE format('DELETE FROM commerceops.%I WHERE id = $1', t) USING r.row_id;
            GET DIAGNOSTICS n = ROW_COUNT;
            deleted := deleted + n;
        END LOOP;
    END LOOP;
    DELETE FROM lab_objects;
    RETURN format('%s lab satiri silindi.', deleted);
END;
$$;

